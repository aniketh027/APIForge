// Target-independent effective identity and service-policy primitives.
// Semantic preflight can use these without invoking the post-IR planner.
const POLICY_VERSION = 1;
const COLLECTION_RESERVED_PARAMS = ['page', 'limit', 'sort', 'order'];
const PROTOTYPE_COLUMNS = ['__proto__', '__defineGetter__', '__defineSetter__', '__lookupGetter__', '__lookupSetter__'];

function stableId(kind, ...names) {
    return kind + ':' + names.map(name => encodeURIComponent(String(name))).join('/');
}

function identity(entity) {
    if (entity?.key?.fieldId) {
        const field = entity.fields.find(item => item.id === entity.key.fieldId && item.origin.kind === 'implicit_key') ||
            entity.fields.find(item => item.id === entity.key.fieldId && item.constraints.includes('PRIMARY_KEY')) ||
            entity.fields.find(item => item.id === entity.key.fieldId);
        return { field, name: field.name, dataType: field.dataType,
            origin: field.origin.kind === 'implicit_key' ? 'implicit' : 'explicit', generation: entity.key.generation };
    }
    const field = entity?.fields?.find(item => item.constraints?.includes('PRIMARY_KEY')) || null;
    const generation = !field || (field.dataType === 'INT' && field.defaultValue == null) ? 'database_integer'
        : field.dataType === 'UUID' && field.defaultValue == null ? 'runtime_uuid' : 'none';
    return { field, name: field ? field.name : 'id', dataType: field ? field.dataType : 'INT',
        origin: field ? 'explicit' : 'implicit', generation };
}

function legacyKey(entity) {
    if (entity?.key?.fieldId) return keyFromPlan(entity);
    const key = identity(entity), generation = key.generation === 'database_integer' ? 'auto_increment' : key.generation;
    return key.field ? { ...key.field, origin: key.origin, autoGenerated: generation !== 'none', generation }
        : { name: key.name, dataType: key.dataType, origin: key.origin, autoGenerated: true, generation };
}

function relationshipTopology(source, target, relation) {
    if (!source || !target) return null;
    const cardinality = relation.cardinality || relation.relationType;
    if (cardinality === 'MANY_TO_MANY') return { kind: 'junction', source, target,
        sourceKey: identity(source), targetKey: identity(target), onDelete: 'cascade' };
    const receiver = cardinality === 'MANY_TO_ONE' ? source : target;
    const referenced = cardinality === 'MANY_TO_ONE' ? target : source;
    const unique = cardinality === 'ONE_TO_ONE';
    return { kind: 'foreign_key', receiver, referenced, referencedKey: identity(referenced),
        nullable: true, unique, onDelete: unique ? 'cascade' : 'set_null' };
}

function declaredEntitiesFromIR(ir) {
    const entities = new Map();
    for (const instruction of Array.isArray(ir?.instructions) ? ir.instructions : []) {
        if (instruction.op !== 'CREATE_ENTITY' && instruction.op !== 'ADD_FIELD') continue;
        if (!entities.has(instruction.entity)) entities.set(instruction.entity, { name: instruction.entity, fields: [] });
        if (instruction.op === 'ADD_FIELD') entities.get(instruction.entity).fields.push({
            name: instruction.field, dataType: instruction.dataType,
            ...(instruction.dataType === 'ENUM' ? { enumValues: [...instruction.enumValues] } : {}),
            constraints: instruction.constraints || [], validations: instruction.validations || [],
            defaultValue: instruction.defaultValue || null, line: instruction.line
        });
    }
    return [...entities.values()];
}

function relationsFromIR(ir) {
    return (Array.isArray(ir?.instructions) ? ir.instructions : []).filter(instruction => instruction?.op === 'CREATE_RELATION').map(instruction => ({
        sourceEntity: instruction.sourceEntity, relationName: instruction.relationName,
        targetEntity: instruction.targetEntity, relationType: instruction.relationType, line: instruction.line
    }));
}

function fieldViews(entity, view = 'declared') {
    const declared = entity.fields.filter(field => field.origin.kind === 'declared');
    const implicit = entity.fields.filter(field => field.origin.kind === 'implicit_key');
    switch (view) {
        case 'declared': case 'model': return declared;
        case 'base': return [...implicit, ...declared];
        case 'query': return [...implicit, ...declared].filter(field => field.roles.http.collection.candidate);
        case 'create': return declared.filter(field => field.roles.http.create.acceptance === 'write');
        case 'update': return declared.filter(field => field.roles.http.update.acceptance === 'write');
        case 'read': return entity.fields.filter(field => field.roles.http.read.exposed);
        case 'createResult': return [...declared, ...implicit].filter(field => field.roles.http.createResult.exposed);
        default: throw new Error('Unknown Effective Schema Plan field view: ' + view);
    }
}

function legacyField(field, provenance = {}) {
    return { name: field.name, dataType: field.dataType,
        ...(field.dataType === 'ENUM' ? { enumValues: [...field.enumValues] } : {}),
        constraints: [...field.constraints], validations: field.validations.map(value => ({ ...value })),
        defaultValue: field.defaultValue ? { ...field.defaultValue } : null,
        line: provenance[field.id]?.line ?? undefined };
}

function keyFromPlan(entity, provenance = {}) {
    const key = identity(entity), generation = key.generation === 'database_integer' ? 'auto_increment' : key.generation;
    return key.origin === 'explicit'
        ? { ...legacyField(key.field, provenance), origin: key.origin, autoGenerated: generation !== 'none', generation }
        : { name: key.name, dataType: key.dataType, origin: key.origin, autoGenerated: true, generation };
}

function legacyEntity(entity, provenance = {}) {
    return { name: entity.sourceName, fields: fieldViews(entity).map(field => legacyField(field, provenance)) };
}

function legacyRelation(relation, plan, provenance = {}) {
    const source = plan.entities.find(entity => entity.id === relation.sourceEntityId);
    const target = plan.entities.find(entity => entity.id === relation.targetEntityId);
    return { sourceEntity: source?.sourceName || decodeURIComponent(relation.sourceEntityId.slice('entity:'.length)),
        relationName: relation.relationName, targetEntity: target?.sourceName || decodeURIComponent(relation.targetEntityId.slice('entity:'.length)),
        relationType: relation.cardinality, line: provenance[relation.id]?.line ?? undefined };
}

function readNormalizationFields(entity) {
    return entity.fields.filter(field => field.origin.kind === 'declared' ||
        (field.origin.kind === 'relationship_fk' && field.dataType === 'UUID'));
}

function readMetadata(entityOrFields) {
    const fields = Array.isArray(entityOrFields) ? entityOrFields : readNormalizationFields(entityOrFields);
    return {
        booleanFields: fields.filter(field => field.dataType === 'BOOLEAN').map(field => field.name),
        temporalFields: fields.filter(field => ['DATE', 'TIMESTAMP'].includes(field.dataType))
            .map(field => ({ name: field.name, dataType: field.dataType })),
        uuidFields: fields.filter(field => field.dataType === 'UUID')
            .map(field => ({ name: field.name, nullable: field.storage.nullable }))
    };
}

function createPresence(field, key) {
    return !!field.constraints?.includes('REQUIRED') && field.defaultValue == null &&
        !(key.generation !== 'none' && field.name === key.name);
}

function writeMetadata(entity) {
    return fieldViews(entity).map(field => ({ name: field.name, dataType: field.dataType,
        required: !field.roles.http.create.nullable, requiredOnCreate: field.roles.http.create.required,
        validations: field.validations.map(value => ({ ...value })),
        ...(field.dataType === 'ENUM' ? { enumValues: [...field.enumValues] } : {}) }));
}

function modelWriteMetadata(entity) {
    const fields = fieldViews(entity), key = identity(entity);
    return {
        temporalFields: fields.filter(field => ['DATE', 'TIMESTAMP'].includes(field.dataType)).map(field => ({
            name: field.name, dataType: field.dataType, required: !!field.constraints.includes('REQUIRED') })),
        uuidFields: fields.filter(field => field.dataType === 'UUID').map(field => ({
            name: field.name, required: !!field.constraints.includes('REQUIRED'), requiredOnCreate: createPresence(field, key) }))
    };
}

function capabilities(plan, entity = null) {
    const temporal = item => fieldViews(item).some(field => ['DATE', 'TIMESTAMP'].includes(field.dataType));
    const uuid = item => fieldViews(item).some(field => field.dataType === 'UUID');
    const prototypeColumns = plan.entities.some(item => fieldViews(item).some(field => PROTOTYPE_COLUMNS.includes(field.name))) ||
        plan.relations.some(relation => relation.names && [relation.names.sourceFk, relation.names.targetFk].some(name => PROTOTYPE_COLUMNS.includes(name)));
    const global = { temporal: plan.entities.some(temporal), uuid: plan.entities.some(uuid), prototypeColumns };
    if (!entity) return global;
    const targets = plan.relations.filter(relation => relation.sourceEntityId === entity.id)
        .map(relation => plan.entities.find(item => item.id === relation.targetEntityId)).filter(Boolean);
    return { ...global, temporalWrites: temporal(entity), uuidWrites: uuid(entity),
        temporalRuntime: temporal(entity) || targets.some(temporal),
        uuidRuntime: readMetadata(entity).uuidFields.length > 0 || targets.some(target => readMetadata(target).uuidFields.length > 0),
        uuidController: uuid(entity) || targets.some(target => identity(target).dataType === 'UUID') };
}

module.exports = { POLICY_VERSION, COLLECTION_RESERVED_PARAMS, stableId, identity, legacyKey, relationshipTopology,
    declaredEntitiesFromIR, relationsFromIR, fieldViews, legacyField, keyFromPlan, legacyEntity, legacyRelation,
    readNormalizationFields, readMetadata, createPresence, writeMetadata, modelWriteMetadata, capabilities };

function compile(source) {
    const ast = Parser.parse(Lexer.tokenize(source)), semantic = Semantic.analyze(ast);
    assert.equal(semantic.valid, true, JSON.stringify(semantic.errors));
    const ir = IR.generate(ast, semantic), optimized = Optimizer.optimize(ir).ir;
    return { ast, ir, optimized, candidate: schema.buildFromIR(optimized) };
}
const entity = (candidate, name) => candidate.plan.entities.find(item => item.sourceName === name);
const field = (entity, name, origin = 'declared') => entity.fields.find(item => item.name === name && item.origin.kind === origin);
const fieldNames = (entity, view) => policy.fieldViews(entity, view).map(item => item.name);
function assertPlain(value) {
    if (value === null || ['string', 'boolean'].includes(typeof value)) return;
    if (typeof value === 'number') { assert(Number.isFinite(value)); return; }
    assert.equal(typeof value, 'object');
    assert(!(value instanceof Map)); assert(!(value instanceof Set));
    for (const child of Object.values(value)) assertPlain(child);
}
function freeze(value) {
    if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
    for (const key of Reflect.ownKeys(value)) freeze(value[key]);
    return Object.freeze(value);
}
function load(source, requireImpl) {
    const module = { exports: {} };
    vm.compileFunction(source, ['require', 'module'])(requireImpl, module);
    return module.exports;
}
function runtime(files, name, row) {
    const calls = [], content = path => files.find(file => file.path === path).content;
    const pool = { query: async (sql, values) => {
        calls.push({ sql, values });
        return sql.startsWith('INSERT') ? [{ insertId: 25 }] : sql.startsWith('UPDATE') ? [{ affectedRows: 1 }] : [[{ ...row }]];
    } };
    const Model = load(content('models/' + name + '.js'), dependency => dependency === '../config/db' ? pool : require(dependency));
    const Controller = load(content('controllers/' + names.lowerFirst(name) + 'Controller.js'), dependency => {
        if (dependency === '../models/' + name) return Model;
        throw new Error('Unexpected generated controller import: ' + dependency);
    });
    return { Model, Controller, calls };
}
async function invoke(controller, method, body) {
    const res = { code: 200, status(code) { this.code = code; return this; }, json(value) { this.body = value; return this; } };
    await controller[method]({ body, params: { id: '25' } }, res);
    return res;
}


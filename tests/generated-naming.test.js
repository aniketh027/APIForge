const assert = require('assert/strict');
const vm = require('vm');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const express = require('express');
const { BASE, baselineModule, analyze, compile, syntax, content } = require('./v1-hardening-helpers');
const baselineSemantic = baselineModule('src/semantic/analyzer.js');
const baselineCodegen = baselineModule('src/codegen/codegen.js');
const { CODES, WARNING_CODES } = require('../src/utils/diagnostics');
let groups = 0;
async function test(name, fn) { await fn(); console.log('  PASS ' + name); groups++; }
(async () => {
    await test('pinned baseline accepts broken names; corrective rejection fails there', () => {
        for (const source of ['ENTITY Student id INT PRIMARY KEY ENTITY student id INT PRIMARY KEY',
            'ENTITY Foo id INT PRIMARY KEY ENTITY FOO id INT PRIMARY KEY',
            'ENTITY Category id INT PRIMARY KEY ENTITY Categorie id INT PRIMARY KEY',
            'ENTITY Item id INT PRIMARY KEY name STRING Name INT']) {
            assert.equal(analyze(source, baselineSemantic).semantic.valid, true);
            assert.throws(() => assert.equal(analyze(source, baselineSemantic).semantic.valid, false));
            const s = analyze(source).semantic;
            assert.equal(s.valid, false); assert(s.diagnostics.some(d => d.code === 'SEM034'));
            assert.equal(s.warnings.length, 0);
            const d = s.diagnostics.find(d => d.code === 'SEM034');
            assert(d.line && d.column && d.endColumn > d.column); assert(d.hint);
        }
        const ast = analyze('ENTITY Student id INT PRIMARY KEY ENTITY student id INT PRIMARY KEY', baselineSemantic).ast;
        const ir = require('../src/ir/generator').generate(ast, baselineSemantic.analyze(ast));
        const old = baselineCodegen.generate(ir, false).files;
        assert(old.length > new Set(old.map(f => f.path)).size);
        assert.throws(() => syntax(old), SyntaxError);
        assert.throws(() => require('../src/codegen/codegen').generate(ir, false), /collision/);
    });
    await test('Windows devices reject; legal mixed-case targets retain every generated byte and phases', () => {
        for (const name of ['CON', 'nul', 'COM1', 'lpt9']) assert.equal(analyze(`ENTITY ${name} id INT PRIMARY KEY`).semantic.valid, false);
        for (const source of ['ENTITY FooBar id INT PRIMARY KEY ENTITY FoobarOther code STRING PRIMARY KEY',
            'ENTITY Student id INT PRIMARY KEY name STRING REQUIRED ENTITY Course code STRING PRIMARY KEY RELATION Student enrolls Course MANY_TO_MANY',
            'ENTITY Item value STRING']) {
            const c = compile(source); syntax(c.files);
            assert.deepEqual(c.files, baselineCodegen.generate(c.optimized, false).files);
            const old = analyze(source, baselineSemantic);
            assert.deepEqual(JSON.parse(JSON.stringify(c.ast)), JSON.parse(JSON.stringify(old.ast)));
            assert.deepEqual(JSON.parse(JSON.stringify(c.semantic.symbolTable)), JSON.parse(JSON.stringify(old.semantic.symbolTable)));
            assert.deepEqual(c.semantic.warnings, old.semantic.warnings);
        }
    });
    await test('prototype-sensitive entities fields relations survive own-key registries and OpenAPI', () => {
        for (const name of ['__proto__', 'constructor', 'toString', 'entities', 'relations']) {
            const source = `ENTITY ${name} key STRING PRIMARY KEY __proto__ STRING constructor INT toString BOOLEAN ENTITY Target id INT PRIMARY KEY RELATION ${name} __proto__ Target ONE_TO_MANY`;
            const c = compile(source); syntax(c.files);
            assert(Object.hasOwn(c.semantic.symbolTable, name));
            assert(Object.keys(c.semantic.symbolTable).includes(name));
            assert(Object.hasOwn(c.semantic.symbolTable[name].fields, '__proto__'));
            assert(Object.hasOwn(c.semantic.relations, '__proto__'));
            const doc = JSON.parse(content(c.files, 'swagger.json'));
            assert(Object.hasOwn(doc.components.schemas, name));
            assert(Object.hasOwn(doc.components.schemas[name].properties, '__proto__'));
            const old = analyze(source, baselineSemantic);
            assert(!Object.keys(old.semantic.symbolTable[name]?.fields || {}).includes('__proto__'));
            assert.equal(Object.getPrototypeOf(c.semantic.symbolTable), null);
            assert.equal(Object.getPrototypeOf(c.semantic.symbolTable[name].fields), null);
            // Execute the actual frontend renderer using the API-serializable inventory.
            const context = { result: null }; vm.createContext(context);
            const frontend = fs.readFileSync(path.resolve(__dirname, '../frontend/app.js'), 'utf8');
            const renderer = frontend.slice(frontend.indexOf('function displayDataType'), frontend.indexOf('// RENDER: IR INSTRUCTIONS'));
            const escape = frontend.match(/function escapeHtml\([^]*?\n\}/)[0];
            vm.runInContext(escape + '\n' + renderer, context);
            context.inventory = JSON.parse(JSON.stringify(c.semantic.symbolTable));
            vm.runInContext('result = renderSymbolTable(inventory)', context);
            assert(context.result.includes(name)); assert(context.result.includes('__proto__'));
        }
        assert.equal({}.polluted, undefined);
    });
    await test('existing diagnostic assignments and warnings are unchanged', () => {
        const old = baselineModule('src/utils/diagnostics.js');
        assert.equal(Object.values(old.CODES).flatMap(Object.values).length, 62);
        for (const [phase, mapping] of Object.entries(old.CODES)) for (const [symbol, code] of Object.entries(mapping)) assert.equal(CODES[phase][symbol], code);
        assert.deepEqual(WARNING_CODES, old.WARNING_CODES);
    });
    await test('real compiler HTTP and CLI reject before IR/artifacts; protected output remains intact', async () => {
        const source = 'ENTITY Category id INT PRIMARY KEY ENTITY Categorie id INT PRIMARY KEY';
        const app = express(); app.use(express.json()); app.use('/api', require('../src/api/compiler-api'));
        const server = app.listen(0, '127.0.0.1');
        try {
            await new Promise(resolve => server.once('listening', resolve));
            const response = await fetch(`http://127.0.0.1:${server.address().port}/api/compile`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ source }) });
            const body = await response.json(); assert.equal(response.status, 422);
            assert.equal(body.phaseStates.ir, 'skipped'); assert.equal(body.phaseStates.codegen, 'skipped');
            assert.equal(body.generatedFiles, undefined); assert.equal(body.diagnostic.code, 'SEM034');
        } finally { await new Promise(resolve => server.close(resolve)); }
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'apiforge-naming-'));
        try {
            fs.writeFileSync(path.join(dir, 'bad.apiforge'), source);
            const child = spawnSync(process.execPath, [path.resolve(__dirname, '../index.js'), 'bad.apiforge'], { cwd: dir, encoding: 'utf8', windowsHide: true });
            assert.equal(child.status, 1); assert(!fs.existsSync(path.join(dir, 'output')));
        } finally { fs.rmSync(dir, { recursive: true, force: true }); }
    });
    console.log(`Generated naming: ${groups} groups PASS; baseline ${BASE}`);
})().catch(error => { console.error(error); process.exitCode = 1; });
